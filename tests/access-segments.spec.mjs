import { test, expect } from '@playwright/test';
import { createBackend, graphPayload } from './gas-harness.mjs';
import { COLLECTION_SEGMENTS } from '../src/workflow/segments.js';

async function setup(page) {
  const backend = createBackend({ bypassAuth: false });
  const admin = backend.request('login', { correo: 'admin@example.test', password: 'test-password' }).data;
  const request = (action, data = {}) => backend.request(action, { ...data, sessionToken: admin.sessionToken });
  request('saveReader', { password: 'test-password', correo: 'reader@example.test', nombre: 'Lector' });
  const folder = request('saveFolder', { nombre: 'Cliente principal' }).data;
  const team = request('createTeam', { nombre: 'Cobranza', carpetaId: folder.id, etiqueta: '#Cobranza' }).data;
  const process = request('createProcess', { nombre: 'Negociación de deuda', teamId: team.id }).data;
  const payload = graphPayload(team, process);
  payload.flow.nombre = 'Playbook de cobranza'; payload.flow.segmentos = structuredClone(COLLECTION_SEGMENTS);
  payload.nodes.forEach((n, i) => { n.metadata = { segmentId: i < 2 ? 'presentacion' : 'registro', editorPosition: { x: i * 400, y: i * 240 } }; });
  const graph = request('saveFullFlow', payload).data;
  await page.route('https://script.google.com/**', async route => {
    const req = route.request(), { action, ...data } = req.method() === 'POST' ? req.postDataJSON() : Object.fromEntries(new URL(req.url()).searchParams);
    await route.fulfill({ json: backend.request(action, data, req.method()) });
  });
  return { backend, request, graph, team, folder };
}
async function login(page, role) {
  await page.getByLabel('Correo', { exact: true }).fill(role + '@example.test');
  await page.getByLabel('Contraseña', { exact: true }).fill('test-password');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.getByText('Biblioteca de flujos', { exact: true })).toBeVisible();
}
test('login y creación/restablecimiento de lectores usan solo Code.gs', async ({ page }) => {
  await setup(page);
  const external = [];
  page.on('request', req => { if (['fetch', 'xhr'].includes(req.resourceType()) && req.url().startsWith('https://') && !req.url().startsWith('https://script.google.com/')) external.push(req.url()); });
  await page.goto('/');
  await page.getByLabel('Correo', { exact: true }).fill('admin@example.test');
  await page.getByLabel('Contraseña', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Credenciales incorrectas');
  await login(page, 'admin');
  await page.getByRole('button', { name: 'Usuarios', exact: true }).click();
  await page.getByLabel('Nombre', { exact: true }).fill('Nuevo lector');
  await page.getByLabel('Correo', { exact: true }).fill('nuevo@example.test');
  await page.getByLabel('Contraseña', { exact: true }).fill('contraseña-inicial-segura');
  await page.getByRole('button', { name: 'Guardar lector', exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: 'nuevo@example.test' });
  await expect(row).toContainText('Nuevo lector');
  await row.getByRole('button', { name: 'Editar lector' }).click();
  await page.getByLabel('Contraseña', { exact: true }).fill('contraseña-nueva-segura');
  await page.getByRole('button', { name: 'Guardar lector', exact: true }).click();
  await expect(page.getByLabel('Contraseña', { exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'Cerrar sesión' }).click();
  await expect(page.getByRole('button', { name: 'Iniciar sesión', exact: true })).toBeVisible();
  await page.getByLabel('Correo', { exact: true }).fill('nuevo@example.test');
  await page.getByLabel('Contraseña', { exact: true }).fill('contraseña-nueva-segura');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.getByText('Biblioteca de flujos', { exact: true })).toBeVisible();
  await expect(page.getByText('Solo lectura', { exact: false })).toBeVisible();
  expect(external).toEqual([]);
});
