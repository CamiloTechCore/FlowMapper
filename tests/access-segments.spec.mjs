test('administrador edita segmento, revisión y mejora; el color y los IDs persisten', async ({ page }) => {
  await page.setViewportSize({ width: 1500, height: 1000 });
  const { graph, request } = await setup(page);
  await page.goto('/'); await login(page, 'admin');
  await page.goto('/flujos/' + graph.flow.id);
  await page.getByRole('button', { name: 'Editar flujo', exact: true }).click();
  await page.getByLabel('Segmento del nodo', { exact: true }).selectOption('registro');
  await page.getByLabel('Revisión del criterio documental', { exact: true }).selectOption('no_aplica');
  await page.getByLabel('Justificación de calidad', { exact: true }).fill('Cliente terminó la interacción');
  await page.getByLabel('Error u oportunidad de mejora y optimización propuesta').fill('Precisar el criterio de tipificación');
  const segment = page.locator('.wf-inspector details[data-segment-id="registro"]');
  await segment.locator('summary').click();
  await segment.getByLabel('Nombre', { exact: true }).fill('Registro consistente');
  await segment.getByLabel('Color', { exact: true }).fill('#a21caf');
  await page.getByRole('button', { name: 'Guardar avance', exact: true }).click();
  await expect(page.locator('.wf-message')).toContainText('Avance guardado');
  const saved = request('getFullFlow', { flowId: graph.flow.id }).data;
  expect(saved.nodes[0].id).toBe(graph.nodes[0].id);
  expect(saved.nodes[0].metadata.calidad.estado).toBe('no_aplica');
  expect(saved.flow.segmentos.find(s => s.id === 'registro').color).toBe('#a21caf');
  await page.getByRole('button', { name: 'Cerrar constructor', exact: true }).click();
  await page.reload();
  await expect(page.getByLabel('Segmentos del flujo')).toContainText('Registro consistente');
  await expect(page.locator('.diagram-node[data-segment="registro"]').first()).toHaveCSS('--segment-color', '#a21caf');
  await page.goto('/flujos/' + graph.flow.id + '?nodo=' + graph.nodes[0].id);
  await expect(page.getByLabel('Detalle del nodo')).toContainText('Precisar el criterio de tipificación');
  await page.screenshot({ path: 'test-results/segments-admin.png', fullPage: true });
});

test('administrador organiza carpetas y desactiva lectores desde la interfaz', async ({ page }) => {
  const { request, team, graph } = await setup(page);
  await page.goto('/'); await login(page, 'admin');
  await page.getByRole('button', { name: '+ Nueva carpeta', exact: true }).click();
  await page.locator('.folder-form').getByLabel('Nombre', { exact: true }).fill('Operación regional');
  await page.locator('.folder-form').getByLabel('Descripción', { exact: true }).fill('Equipo de cobranza regional');
  await page.getByRole('button', { name: 'Guardar carpeta', exact: true }).click();
  await expect(page.locator('.folder-form')).toHaveCount(0);
  const folder = request('getFolders').data.find(f => f.nombre === 'Operación regional');
  await page.goto('/equipos');
  await page.getByRole('button', { name: 'Editar equipo Cobranza', exact: true }).click();
  await page.getByRole('combobox', { name: 'Carpeta / grupo principal' }).selectOption(folder.id);
  await page.getByRole('button', { name: 'Guardar equipo', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(request('getTeams').data.find(t => t.id === team.id).carpetaId).toBe(folder.id);
  await page.goto('/');
  await page.getByLabel('Filtrar por carpeta').selectOption(folder.id);
  await expect(page.getByRole('button', { name: graph.flow.nombre, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Usuarios', exact: true }).click();
  await page.getByRole('button', { name: 'Editar lector', exact: true }).click();
  await page.getByLabel('Acceso activo', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Guardar lector', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: 'reader@example.test' })).toContainText('Desactivado');
  expect(request('getUsers').data.find(u => u.correo === 'reader@example.test').activo).toBe(false);
});
